#!/usr/bin/env node
/**
 * Bundles every skills/<name>/SKILL.md into a generated TS module, so the
 * markdown files stay the single source of truth while tsup's dist/ (and the
 * Docker image built from it) carries their content without a runtime file
 * lookup. Runs as part of `build:app`, like the browser bundles.
 */
import { readFileSync, readdirSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const skillsDir = path.join(root, 'skills');

const skills = existsSync(skillsDir)
  ? readdirSync(skillsDir, { withFileTypes: true })
      .filter((entry) => entry.isDirectory() && existsSync(path.join(skillsDir, entry.name, 'SKILL.md')))
      .map((entry) => ({
        directory: entry.name,
        markdown: readFileSync(path.join(skillsDir, entry.name, 'SKILL.md'), 'utf8'),
      }))
      .sort((a, b) => a.directory.localeCompare(b.directory))
  : [];

const outPath = path.join(root, 'src', 'tools', 'skillsBundle.generated.ts');
writeFileSync(
  outPath,
  [
    '// GENERATED by scripts/build-skills.mjs from skills/*/SKILL.md — do not edit by hand.',
    `export const BUNDLED_SKILLS: { directory: string; markdown: string }[] = ${JSON.stringify(skills, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(`Wrote ${path.relative(root, outPath)} (${skills.length} skills)`);
