#!/usr/bin/env node
// Gate: a PR must close an issue that a maintainer has admitted as `ready`.
//
// Ported from ifc-lite, where this is the mechanism that stops parallel agents
// from inventing work. The value is not the label — it is that the decision
// "this should be worked on" happens once, in public, before the branch exists.
// Without it, agents each pick something plausible and the review queue fills
// with changes nobody asked for.
//
// Advisory by default. A gate that lands enforcing on day one blocks the PR
// that introduces it, and every in-flight PR besides. Set `--enforce` (or
// ISSUE_QUEUE_ENFORCE=1) once the queue is populated and the team has adjusted.
//
// Usage:
//   node scripts/check-issue-queue.mjs --pr 123
//   node scripts/check-issue-queue.mjs --pr 123 --enforce

import { execFileSync } from 'node:child_process';

const REPO = process.env.ORCHESTRATOR_REPO ?? 'bruadam/dalux-build';
const MODE_ENFORCE = process.argv.includes('--enforce') || process.env.ISSUE_QUEUE_ENFORCE === '1';

function arg(name) {
  const i = process.argv.indexOf(name);
  return i >= 0 ? process.argv[i + 1] : undefined;
}

function ghJson(args, { quiet = false } = {}) {
  try {
    return JSON.parse(execFileSync('gh', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }));
  } catch (error) {
    if (!quiet) process.stderr.write(`gh failed: ${String(error.message).split('\n')[0]}\n`);
    return null;
  }
}

/** `Closes #12`, `fixes #12`, `resolves #12` — GitHub's own closing keywords. */
export function closingRefs(text) {
  const out = new Set();
  const re = /\b(?:close[sd]?|fix(?:e[sd])?|resolve[sd]?)\b[:\s]+#(\d+)/gi;
  for (const m of (text ?? '').matchAll(re)) out.add(Number(m[1]));
  return [...out];
}

function finish(ok, lines) {
  for (const l of lines) console.log(l);
  if (ok) return 0;
  if (MODE_ENFORCE) {
    console.log('\nMode: ENFORCING — this is a blocking failure.');
    return 1;
  }
  console.log('\nMode: advisory — not blocking. Enable with --enforce once the queue is in use.');
  return 0;
}

function main() {
  const prNumber = arg('--pr') ?? process.env.PR_NUMBER;
  if (!prNumber) {
    console.log('No --pr given; nothing to check.');
    return 0;
  }

  const pr = ghJson(['pr', 'view', prNumber, '--repo', REPO, '--json', 'number,title,body,labels']);
  if (!pr) return finish(false, ['Could not read the PR.']);

  // A release PR is generated by Changesets and closes nothing by design.
  if ((pr.labels ?? []).some((l) => /release|dependencies/i.test(l.name))) {
    return finish(true, [`✔ #${pr.number} is a release/dependency PR — queue gate does not apply.`]);
  }

  const refs = closingRefs(pr.body);
  if (!refs.length) {
    return finish(false, [
      `❌ #${pr.number} closes no issue.`,
      '',
      'Add `Closes #<n>` to the PR body. If no issue exists, file one first and let',
      'a maintainer label it `ready` — that is the admission step the queue exists for.',
    ]);
  }

  const problems = [];
  const good = [];
  const prRefs = [];
  for (const n of refs) {
    // `repos/:owner/:repo/issues/:n` answers for issues AND pull requests, and
    // marks the latter with a `pull_request` key. `gh issue view` simply errors
    // on a PR number, which is how the first version of this gate produced a
    // raw gh failure on a batch PR that closed other PRs.
    const item = ghJson(['api', `repos/${REPO}/issues/${n}`, '--jq', '{number,title,state,labels:[.labels[].name],isPr:(has("pull_request"))}']);
    if (!item) { problems.push(`#${n}: could not be read`); continue; }
    if (item.isPr) { prRefs.push(`#${n} ${item.title}`); continue; }
    if ((item.labels ?? []).includes('ready')) good.push(`#${n} ${item.title}`);
    else problems.push(`#${n} is not labelled \`ready\` (has: ${(item.labels ?? []).join(', ') || 'no labels'})`);
  }

  // A PR that supersedes other PRs — the batched dependency pattern this repo
  // already uses — closes no issue by design and is not evading the queue.
  if (!good.length && !problems.length && prRefs.length) {
    return finish(true, [
      `✔ #${pr.number} supersedes ${prRefs.length} pull request(s) and closes no issue:`,
      ...prRefs.map((r) => `    ${r}`),
      '',
      'Treated as a batch/superseding PR, so the queue gate does not apply.',
    ]);
  }

  if (problems.length) {
    return finish(false, [
      `❌ #${pr.number}: referenced issue(s) not admitted:`,
      ...problems.map((p) => `    ${p}`),
      '',
      'Only a maintainer can apply `ready`. Ask for it on the issue rather than',
      'self-admitting — see AGENTS.md, *Working in parallel*.',
    ]);
  }

  return finish(true, [`✔ #${pr.number} closes admitted work: ${good.join('; ')}`]);
}

process.exit(main());
